  export const getStatusColor = (status) => {
    switch (status.toLowerCase()) { // Normalize case to lowercase
      case "interested":
        return "green";
      case "call back":
        return "yellow";
      case "not interested":
        return "red";
      case "switch off":
        return "orange";
      case "ringing":
        return "purple";
      case "converted":
        return "green";
      case "waiting":
        return "darkpink";
        case "pending":
          return "orange";
          case "joining":
            return "green";
            case "dnd":
              return "red";
      default:
        return "black"; // Default color
    }
  };


  
